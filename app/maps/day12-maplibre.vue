<script setup lang="ts">
// Day 12: Power, on MapLibre GL JS (the hidden page /day/12-maplibre) — the same three looks at the
// power of the world's ocean waves as the Navara map (day12.vue), the same code running them
// (waveSim.ts), shown on MapLibre's globe through a custom layer (waveGlobeLayer.ts). MapLibre
// has no bloom, so the brightest seas don't glow; its own atmosphere stands in for Navara's limb
// glow, and there are no stars. With ?gui=1, the same panel tunes them as they run
import * as maplibregl from 'maplibre-gl'
import 'maplibre-gl/dist/maplibre-gl.css'
// MapLibre finds its worker next to its own module, which Vite's bundling moves: point it there
import workerUrl from 'maplibre-gl/dist/maplibre-gl-worker.mjs?url'
import type GUI from 'lil-gui'
import { waveGlobeLayer, type WaveGlobeLayer } from './lib/waveGlobeLayer'
import { WaveCrestSim } from './lib/waveCrestSim'
import { WaveFluidSim } from './lib/waveFluidSim'
import { MODES, waveGui, type Mode } from './lib/waveGui'
import type { WaveGrid } from './lib/waveSim'
import { WaveStreamSim } from './lib/waveStreamSim'

maplibregl.setWorkerUrl(workerUrl)

// Generated by scripts/day12/fetch_waves.py
const dataBase = `${useRuntimeConfig().app.baseURL}data/day12`

const NIGHT = '#03060f'

// The North Pacific, from Japan out to the storm south of the Aleutians, as on the Navara map
const START = { center: [-178, 38] as [number, number], zoom: 2.15 }
// No closer than about 300 km up, as on the Navara map
const MAX_ZOOM = 5.5

const container = ref<HTMLDivElement>()
const controls = ref<HTMLDivElement>()
const mode = ref<Mode>('fluid')
let map: maplibregl.Map | undefined
let layer: WaveGlobeLayer<Mode> | undefined
let gui: GUI | undefined

onMounted(async () => {
  const [meta, data] = await Promise.all([
    fetch(`${dataBase}/waves.json`).then((r) => r.json()),
    fetch(`${dataBase}/waves.bin`).then((r) => r.arrayBuffer()),
  ])
  if (!container.value) return // unmounted while loading
  const grid: WaveGrid = { ...meta, data: new Uint16Array(data) }

  const m = new maplibregl.Map({
    container: container.value,
    style: {
      version: 8,
      projection: { type: 'globe' },
      sources: {
        // The basemap the Navara map uses (Re:Earth Papers, dark), dimmed to the land's shapes
        papers: { type: 'raster', url: 'https://papers.reearth.land/styles/papers-dark/tilejson.json', tileSize: 512 },
      },
      layers: [
        { id: 'night', type: 'background', paint: { 'background-color': NIGHT } },
        {
          id: 'land',
          type: 'raster',
          source: 'papers',
          paint: { 'raster-brightness-max': 0.55, 'raster-saturation': -0.4, 'raster-contrast': 0.1 },
        },
      ],
      // MapLibre's own atmosphere round the globe, fading as you close in
      sky: { 'atmosphere-blend': ['interpolate', ['linear'], ['zoom'], 0, 0.8, 4, 0.8, 6, 0] },
    },
    center: START.center,
    zoom: START.zoom,
    maxZoom: MAX_ZOOM,
    attributionControl: {
      customAttribution: `Waves: <a href="https://www.ecmwf.int/en/forecasts/datasets/open-data">ECMWF open data</a> (IFS wave model, ${String(meta.time).replace('T', ' ').replace('Z', ' UTC')}), CC BY 4.0`,
    },
  })
  map = m

  // Both looks, only the one shown running; it starts afresh when switched to
  const looks = { fluid: new WaveFluidSim(grid), stream: new WaveStreamSim(grid), crests: new WaveCrestSim(grid) }
  const l = waveGlobeLayer(looks, mode.value)
  layer = l
  m.once('load', () => {
    if (map === m) m.addLayer(l)
  })
  watch(mode, (next) => l.show(next))

  // The panel, only with ?gui=1 (no bloom to tune here)
  if (useRoute().query.gui === '1') {
    gui = waveGui(controls.value, {
      fluid: looks.fluid.params,
      stream: looks.stream.params,
      crests: looks.crests.params,
      setSpeed: (x) => (looks.fluid.speed = looks.stream.speed = looks.crests.speed = x),
      mode: () => mode.value,
      onMode: (f) => watch(mode, f),
    })
  }
})

onBeforeUnmount(() => {
  gui?.destroy()
  gui = undefined
  map?.remove()
  map = undefined
  layer?.dispose()
  layer = undefined
})
</script>

<template>
  <div class="map-canvas day12">
    <div ref="container" class="map-canvas" />
    <div ref="controls" class="controls" />
    <div class="modes" role="group" aria-label="Look">
      <button v-for="(label, key) in MODES" :key="key" type="button" :aria-pressed="mode === key" @click="mode = key">
        {{ label }}
      </button>
    </div>
  </div>
</template>


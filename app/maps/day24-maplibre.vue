/** Sunrise and sunset (hours, JST) on `day` at `lat`/`lng` (NOAA's approximation, to a minute or two). */
function sunTimes(day: string, { lat, lng }: { lat: number; lng: number }): [number, number] {
  const d = new Date(`${day}T12:00:00+09:00`)
  const doy = (d.getTime() - Date.UTC(d.getUTCFullYear(), 0, 0)) / 86_400_000
  const g = ((2 * Math.PI) / 365) * (doy - 1)
  const eqTime =
    229.18 * (0.000075 + 0.001868 * Math.cos(g) - 0.032077 * Math.sin(g) - 0.014615 * Math.cos(2 * g) - 0.040849 * Math.sin(2 * g))
  const decl =
    0.006918 - 0.399912 * Math.cos(g) + 0.070257 * Math.sin(g) - 0.006758 * Math.cos(2 * g) + 0.000907 * Math.sin(2 * g) -
    0.002697 * Math.cos(3 * g) + 0.00148 * Math.sin(3 * g)
  const phi = (lat * Math.PI) / 180
  const ha = (Math.acos(Math.cos((90.833 * Math.PI) / 180) / (Math.cos(phi) * Math.cos(decl)) - Math.tan(phi) * Math.tan(decl)) * 180) / Math.PI
  const jst = (minutesUtc: number) => (minutesUtc + 540) / 60
  return [jst(720 - 4 * (lng + ha) - eqTime), jst(720 - 4 * (lng - ha) - eqTime)]
}

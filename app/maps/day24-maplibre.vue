const cache = new Map<string, Promise<Flows>>()
const dockedCache = new Map<string, Promise<Uint8Array>>()

function loadDocked(file: string): Promise<Uint8Array> {
  let p = dockedCache.get(file)
  if (!p) {
    p = fetch(`${dataURL}/${file}`)
      .then((r) => r.arrayBuffer())
      .then((b) => new Uint8Array(b))
    dockedCache.set(file, p)
  }
  return p
}

const clockLabel = computed(() => {
  const m = Math.floor(Math.min(now.value, 23.999) * 60)
  return `${String(Math.floor(m / 60)).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}`
})

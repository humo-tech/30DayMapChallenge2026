// The timeline's bars, on one scale for both days so the rain shows
const BAR_H = 44
const barMax = ref(1)

/** One run's flows from its binary records (see scripts/day24/export_flows.py). */
function loadFlows(file: string): Promise<Flows> {
  let p = cache.get(file)
  if (!p) {
    p = fetch(`${dataURL}/${file}`)
      .then((r) => r.arrayBuffer())
      .then((buf) => {
        const dv = new DataView(buf)
        const count = buf.byteLength / 8
        const flows: Flows = {
          count,
          from: new Uint16Array(count),
          to: new Uint16Array(count),
          hour: new Float32Array(count),
          bikes: new Float32Array(count),
        }
        for (let i = 0; i < count; i++) {
          const o = i * 8
          flows.from[i] = dv.getUint16(o, true)
          flows.to[i] = dv.getUint16(o + 2, true)
          flows.hour[i] = dv.getUint8(o + 4)
          flows.bikes[i] = dv.getUint16(o + 6, true) / 1000
        }
        return flows
      })
    cache.set(file, p)
  }
  return p
}

function hourlyOf(flows: Flows): number[] {
  const h = new Array<number>(24).fill(0)
  for (let i = 0; i < flows.count; i++) h[flows.hour[i]!]! += flows.bikes[i]!
  return h
}

// One generation per switch: a run that finishes loading after the next switch is dropped
let generation = 0
async function show() {
  const l = layer
  if (!l || !meta) return
  const gen = ++generation
  const run = meta.runs[`${day.value}_${method.value}`]
  const dockedFile = meta.docked[day.value]
  if (!dockedFile) return
  loading.value = true
  // (a run not there yet leaves the columns without arcs)
  const [flows, docked] = await Promise.all([run ? loadFlows(run.file) : undefined, loadDocked(dockedFile)])
  if (gen !== generation || layer !== l) return
  l.setDocked(docked)
  l.setFlows(flows)
  hourly.value = flows ? hourlyOf(flows) : []
  loading.value = false
}

watch([method, day], show)

// The clock: SPEED hours a second, holds at midnight, then the day starts over
let last = 0
let held = 0
function frame(t: number) {
  const dt = last ? Math.min(0.1, (t - last) / 1000) : 0
  last = t
  if (playing.value) {
    if (now.value >= 24) {
      held += dt
      if (held > HOLD_S) {
        held = 0
        now.value = 0
      }
    } else {
      now.value = Math.min(24, now.value + dt * SPEED)
    }
  }
  raf = requestAnimationFrame(frame)
}

const scrubbing = ref(false)
function scrubTo(e: PointerEvent) {
  const r = (e.currentTarget as HTMLElement).getBoundingClientRect()
  now.value = Math.max(0, Math.min(24, ((e.clientX - r.left) / r.width) * 24))
  held = 0
}
function scrubStart(e: PointerEvent) {
  scrubbing.value = true
  ;(e.currentTarget as HTMLElement).setPointerCapture(e.pointerId)
  scrubTo(e)
}
function scrubMove(e: PointerEvent) {
  if (scrubbing.value) scrubTo(e)
}
function togglePlay() {
  if (!playing.value && now.value >= 24) now.value = 0
  playing.value = !playing.value
}

/** What the layer draws this frame: the clock, how hard it rains, the basemap's tint */
function frameState() {
  const wet = Math.min(1, rainRate(rainToday.value, now.value) / RAIN_HEAVY)
  const [rise, set] = sunTimes(day.value, MAKUHARI)
  const t = now.value
  const smooth = (x: number) => x * x * (3 - 2 * x)
  const ramp = (x: number) => smooth(Math.min(1, Math.max(0, (x + TWILIGHT_H) / (2 * TWILIGHT_H))))
  const light = ramp(t - rise) * (1 - ramp(t - set)) * (1 - RAIN_DIM * wet)
  const warm = Math.exp(-(((t - rise) / TWILIGHT_H) ** 2)) + Math.exp(-(((t - set) / TWILIGHT_H) ** 2))
  const rgb = mix(mix(NIGHT_TINT, DAY_TINT, light), TWILIGHT_TINT, 0.55 * Math.min(1, warm))
  // (set only when it changes by a shade: restyling the map is not free)
  const tint = rgb.map((c) => Math.round(c) / 255)
  const night = 1 - light
  const lift = Math.round((1 + (ROAD_LIFT_NIGHT - 1) * night) * 50) / 50
  const key = `${tint.join()}|${lift}`
  if (map && key !== styled) {
    styled = key
    map.setGlobalStateProperty('tint', tint)
    map.setGlobalStateProperty('lift', lift)
  }
  return { hours: t, wet }
}

/** One color of the style, times the global tint (and `extra`, a global-state number, if given) */
function tinted(color: unknown, extra?: string): unknown {
  const channel = (i: number) => [
    '*',
    ['at', i, ['var', 'c']],
    ['number', ['at', i, ['array', 'number', 3, ['global-state', 'tint']]]],
    ...(extra ? [['number', ['global-state', extra]]] : []),
  ]
  return ['let', 'c', ['to-rgba', color], ['rgb', channel(0), channel(1), channel(2)]]
}

/** The Papers vector style with its colors tinted by global state, and buildings added */
function tintedStyle(papers: maplibregl.StyleSpecification): maplibregl.StyleSpecification {
  const layers = [
    ...papers.layers,
    {
      id: 'buildings',
      type: 'fill-extrusion',
      source: 'v',
      'source-layer': 'buildings',
      minzoom: 13,
      paint: {
        'fill-extrusion-color': '#cfd3da',
        'fill-extrusion-height': ['coalesce', ['get', 'height'], 8],
        'fill-extrusion-base': ['coalesce', ['get', 'min_height'], 0],
        'fill-extrusion-opacity': 0.85,
      },
    },
  ] as maplibregl.LayerSpecification[]
  for (const layer of layers) {
    const paint = (layer.paint ?? {}) as Record<string, unknown>
    // (the background's zoom steps are all white where the map is looked at: one color)
    if (layer.type === 'background') paint['background-color'] = 'rgb(255, 255, 255)'
    const road = /^(roads|railway)_/.test(layer.id)
    for (const [key, value] of Object.entries(paint)) {
      if (key.endsWith('-color')) paint[key] = tinted(value, road ? 'lift' : undefined)
    }
    layer.paint = paint as never
  }
  return {
    ...papers,
    layers,
    state: { tint: { default: [1, 1, 1] }, lift: { default: 1 } },
  } as maplibregl.StyleSpecification
}

onMounted(async () => {
  raf = requestAnimationFrame(frame)
  const box = container.value!
  const [m, data, papers] = await Promise.all([
    fetch(`${dataURL}/${AREA}.json`).then((r) => r.json() as Promise<Meta>),
    fetch(`${dataURL}/rain.json`).then((r) => r.json() as Promise<{ days: Record<string, number[]> }>),
    fetch(PAPERS_STYLE).then((r) => r.json() as Promise<maplibregl.StyleSpecification>),
  ])
  if (!container.value) return // unmounted while loading
  meta = m
  rain.value = data.days

  // The basemap is vector: the Papers style's own layers (earth, water, roads, railways), with
  // the buildings of its Protomaps tiles raised over them, a little, in the same pale grey. Every
  // color goes through the style's global state, `tint` (a multiplier per channel) and `lift`
  // (more for roads), which frameState() sets as the day goes
  const style = tintedStyle(papers)
  const mapView = new maplibregl.Map({
    container: box,
    style,
    center: [camera.lng, camera.lat],
    zoom: zoomFor(camera.distance, camera.lat, box.clientHeight || 800),
    bearing: camera.heading,
    pitch: 90 + camera.pitch,
    maxPitch: 80,
    attributionControl: {
      customAttribution:
        'Station counts: <a href="https://www.hellocycling.jp/">HELLO CYCLING</a> (GBFS); rides guessed from them · Rain: <a href="https://www.data.jma.go.jp/stats/etrn/">JMA</a> AMeDAS Chiba',
    },
  })
  map = mapView

  layer = day24Layer({
    anchor: { lng: m.center[0], lat: m.center[1] },
    stations: m.stations,
    capacity: m.capacity,
    marks: MARKS,
    heading: CAMERA.heading,
    frame: frameState,
  })
  const l = layer
  mapView.on('load', async () => {
    if (map !== mapView) return
    mapView.addLayer(l)
    // One scale for the bars: the busiest hour of any run
    await show()
    const all = await Promise.all(Object.values(m.runs).map((r) => loadFlows(r.file)))
    if (map !== mapView) return
    barMax.value = Math.max(...all.flatMap(hourlyOf))
  })
})

onBeforeUnmount(() => {
  cancelAnimationFrame(raf)
  generation++
  map?.remove()
  map = undefined
  layer?.dispose()
  layer = undefined
})
</script>


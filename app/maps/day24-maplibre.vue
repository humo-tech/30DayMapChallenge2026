/** mm/h over the hour up to `hours` (eased between the 10-minute steps). */
function rainRate(tenMin: number[], hours: number): number {
  const hourTo = (k: number) => {
    let sum = 0
    for (let i = Math.max(0, k - 5); i <= Math.min(tenMin.length - 1, k); i++) sum += tenMin[i]!
    return sum
  }
  const x = hours * 6 - 1
  const k = Math.floor(x)
  return hourTo(k) + (hourTo(k + 1) - hourTo(k)) * (x - k)
}

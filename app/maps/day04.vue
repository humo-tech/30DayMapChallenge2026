<script setup lang="ts">
// Day 4: Clusters — HELLO CYCLING's bike-share stations as 3D spheres, splitting apart as the camera closes in
import ThreeView, { Color, type Layer, type Source } from '@navaramap/three'
import { DefaultPlugin, type DefaultDescriptions } from '@navaramap/three-default-plugin'
import { TileJsonPlugin } from '@navaramap/three-plugins'
import Supercluster, { type PointFeature } from 'supercluster'
import { ClusterSpheresMeshDesc, type ClusterSphere, type ClusterSpheresConfig } from './lib/ClusterSpheresMeshDesc'
import { LimbGlowMeshDesc, type LimbGlowConfig } from './lib/LimbGlowMeshDesc'
import { StarfieldMeshDesc, type StarfieldConfig } from './lib/StarfieldMeshDesc'

// Generated by scripts/day04/extract_stations.py
const baseURL = useRuntimeConfig().app.baseURL
const dataBase = `${baseURL}data/day04`
// Inter Bold, latin subset (SIL OFL 1.1, see public/fonts/Inter-OFL.txt)
const FONT = `${baseURL}fonts/inter-latin-700-normal.woff2`

const NAVY = '#060b1c'
const INK = new Color().setStyle('#1a1a1a')

// Clusters merge points within this many screen px; Navara has no clustering, so supercluster does it
const CLUSTER_RADIUS_PX = 60
const MAX_ZOOM = 16
const ZOOM_BIAS = 1
const TRANSITION_MS = 700
// Sphere diameter in px, by total capacity (docks): it runs from a few to tens of thousands, so
// the diameter grows with its log
const sizeOf = (capacity: number) => 8 + 3.8 * Math.log2(1 + capacity / 5)
// Heat (the glow under the sphere) by station count: 10,000 stations is the hottest
const heatOf = (count: number) => Math.min(1, Math.log10(count) / 4)

// The camera loops: all of Japan -> down into central Tokyo, where the clusters break apart -> back out
const JAPAN_VIEW = { lng: 137.5, lat: 35.2, distance: 3_400_000, heading: 0, pitch: -70, roll: 0 }
const TOKYO_VIEW = { lng: 139.74, lat: 35.68, distance: 30_000, heading: 20, pitch: -50, roll: 0 }
const FLIGHT_MS = 9000
const HOLD_MS = 2500

type StationProps = { capacity: number; i: number }
type Item = ClusterSphere & { count: number; clusterId?: number; leaf?: number }

const container = ref<HTMLDivElement>()
let view: ThreeView<DefaultDescriptions> | undefined
let timer: ReturnType<typeof setTimeout> | undefined
let labelTimer: ReturnType<typeof setTimeout> | undefined

const wait = (ms: number) => new Promise<void>((resolve) => (timer = setTimeout(resolve, ms)))

// The camera tour, with a button to stop and restart it
const touring = ref(true)
let setTouring: ((on: boolean) => void) | undefined

onMounted(async () => {
  const v = new ThreeView<DefaultDescriptions>({
    container: container.value!,
    backgroundColor: new Color().setStyle(NAVY),
    animation: true,
  })
  view = v
  v.addPlugin(new DefaultPlugin())
  const tilejson = new TileJsonPlugin()
  v.addPlugin(tilejson)
  await v.init()
  if (view !== v) return // unmounted while initializing
  v.registerMesh('limbGlow', LimbGlowMeshDesc)
  v.registerMesh('starfield', StarfieldMeshDesc)
  v.registerMesh('clusterSpheres', ClusterSpheresMeshDesc)

  v.setCamera({ ...JAPAN_VIEW, height: 0 })

  // (typed separately: the view's mesh config union only knows the DefaultPlugin descriptors)
  const limbGlow: LimbGlowConfig = { limbGlow: { color: new Color().setStyle('#5b86ff'), intensity: 0.8, scaleHeight: 80_000 } }
  v.addMesh<LimbGlowMeshDesc>(limbGlow)
  const starfield: StarfieldConfig = { starfield: {} }
  v.addMesh<StarfieldMeshDesc>(starfield)

  // The dark sibling of the basemap Navara's own examples use (Re:Earth Papers); the plugin credits it from the TileJSON
  const basemap = await tilejson.addSource({
    type: 'raster-tile',
    url: 'https://papers.reearth.land/styles/papers-dark/tilejson.json',
  })
  if (view !== v) return
  v.addLayer({ type: 'raster', source: basemap })

  const stations: { features: PointFeature<StationProps>[] } = await (await fetch(`${dataBase}/stations.geojson`)).json()
  if (view !== v) return
  // Each station's index rides along as its id, to trace which cluster it sits in at each zoom
  stations.features.forEach((f, i) => (f.properties.i = i))
  const index = new Supercluster<StationProps, { capacity: number }>({
    radius: CLUSTER_RADIUS_PX,
    maxZoom: MAX_ZOOM,
    map: (p) => ({ capacity: p.capacity }),
    reduce: (acc, p) => {
      acc.capacity += p.capacity
    },
  })
  index.load(stations.features)

  const itemsAt = (zoom: number): Item[] =>
    index.getClusters([-180, -85, 180, 85], zoom).map((f) => {
      const [lng, lat] = f.geometry.coordinates as [number, number]
      const p = f.properties
      const count = 'cluster' in p && p.cluster ? p.point_count : 1
      return {
        lng,
        lat,
        size: sizeOf(p.capacity),
        heat: heatOf(count),
        count,
        ...('cluster' in p && p.cluster ? { clusterId: p.cluster_id } : { leaf: (p as StationProps).i }),
      }
    })
  // A station inside the item, and every station -> the item it sits in
  const leafOf = (item: Item) =>
    item.clusterId === undefined ? item.leaf! : (index.getLeaves(item.clusterId, 1)[0]!.properties as StationProps).i
  const ownersOf = (items: Item[]) => {
    const owners = new Map<number, Item>()
    for (const item of items) {
      if (item.clusterId === undefined) owners.set(item.leaf!, item)
      else for (const l of index.getLeaves(item.clusterId, Infinity)) owners.set((l.properties as StationProps).i, item)
    }
    return owners
  }

  const bloom = v.addEffect({ selectiveBloom: { strength: 1.1, radius: 0.5, threshold: 0 } })
  const spheresConfig: ClusterSpheresConfig = { effectIds: [bloom.id], clusterSpheres: { duration: TRANSITION_MS } }
  const spheres = v.addMesh<ClusterSpheresMeshDesc>(spheresConfig)

  // Station counts, centred on the spheres. Navara's `Source.update` doesn't take new inline data, so each
  // zoom step swaps in a fresh source + layer once the spheres have settled
  let metersPerPx = 1
  let labels: { source: Source; layer: Layer } | undefined
  const showLabels = (items: Item[]) => {
    const source = v.addSource({
      type: 'geojson',
      data: {
        type: 'FeatureCollection',
        features: items.flatMap((s) => {
          const text = s.count.toLocaleString('en-US')
          // Sized to span at most 80% of the sphere (Inter Bold digits are ~0.62 em wide);
          // single stations, and spheres too small to hold their number legibly, go without one
          const fontSize = Math.min(16, (0.8 * s.size) / (0.62 * text.length))
          if (s.count === 1 || fontSize < 8) return []
          return [{ type: 'Feature' as const, geometry: { type: 'Point' as const, coordinates: [s.lng, s.lat] }, properties: { text, fontSize, size: s.size } }]
        }),
      },
    })
    const layer = v.addLayer({
      type: 'vector',
      source,
      text: { text: '', font: FONT, color: INK, size: 12, sizeInMeters: true, clampToGround: false, declutter: false, depthTest: false, transparent: true },
    })
    layer.on('featureUpdated', ({ evaluator }) => {
      evaluator.evaluate(
        ({ properties }) => {
          const size = Number(properties?.['size'])
          // At the sphere's centre, one radius up; sized in metres like the spheres so it shrinks with
          // them into the distance
          return { text: String(properties?.['text']), height: 0.5 * size * metersPerPx, size: Number(properties?.['fontSize']) * metersPerPx }
        },
        { filters: ['text', 'fontSize', 'size'] },
      )
    })
    clearLabels()
    labels = { source, layer }
  }
  const clearLabels = () => {
    labels?.layer.delete()
    labels?.source.delete()
    labels = undefined
  }

  // Navara's zoom comes from the camera's height; a tilted camera sees the ground at the view
  // centre farther off, along its line of sight
  const centreZoom = () => {
    const pitch = Math.abs(v.camera.orientation.pitch ?? -90)
    return (v.camera.zoom ?? 0) + Math.log2(Math.sin((pitch * Math.PI) / 180))
  }

  // Each zoom step splits the clusters into their children (zooming in) or gathers them into
  // their parents (zooming out); the numbers come back once the spheres have settled
  let zoom = -1
  let current: Item[] | undefined
  const recluster = () => {
    // Toward the top of a tilted view the ground is farther still, so cluster a level coarser
    const z = Math.max(0, Math.min(MAX_ZOOM + 1, Math.floor(centreZoom() - ZOOM_BIAS)))
    if (z === zoom) return
    const next = itemsAt(z)
    if (current) {
      let owners: Map<number, Item>
      const moves =
        z > zoom
          ? ((owners = ownersOf(current)), next.map((n) => ({ from: owners.get(leafOf(n)) ?? n, to: n })))
          : ((owners = ownersOf(next)), current.map((o) => ({ from: o, to: owners.get(leafOf(o)) ?? o })))
      spheres.ref.transition(moves, next, z > zoom ? 'split' : 'merge')
    } else {
      spheres.ref.set(next)
    }
    zoom = z
    current = next
    clearLabels()
    clearTimeout(labelTimer)
    labelTimer = setTimeout(() => view === v && showLabels(next), TRANSITION_MS)
  }

  v.on('preUpdate', () => {
    const lat = v.camera.positionGeographic.lat
    const m = (156_543.03 * Math.cos((lat * Math.PI) / 180)) / 2 ** centreZoom()
    // Follow the zoom with the numbers' heights, without re-evaluating them every frame
    if (Math.abs(m / metersPerPx - 1) > 0.02) {
      metersPerPx = m
      labels?.layer.forceUpdate()
    }
    spheres.ref.tick(performance.now(), m)
    recluster()
  })


  v.attribution?.add([
    {
      attributionHtml:
        'Stations: <a href="https://www.hellocycling.jp/">HELLO CYCLING</a> (GBFS)',
    },
  ])

  const fly = (to: typeof JAPAN_VIEW) => v.flyTo(to, { duration: FLIGHT_MS, easing: 'cubicInOut' })
  // Each run of the tour gets a number; stopping bumps it, so a stale run quits at its next step
  let run = 0
  const tour = async () => {
    const id = ++run
    const live = () => view === v && id === run
    // Head for whichever end of the loop is farther from where the camera is now
    let close = v.camera.positionGeographic.height > 500_000
    while (live()) {
      await wait(HOLD_MS)
      if (!live()) return
      // A flight resolves false when it is cut short: by the user grabbing the camera (hand it
      // over and stop) or by the stop button (already stopped)
      if (!(await fly(close ? TOKYO_VIEW : JAPAN_VIEW))) {
        if (live()) setTouring?.(false)
        return
      }
      close = !close
    }
  }
  setTouring = (on) => {
    touring.value = on
    if (on) {
      tour()
      return
    }
    run++
    clearTimeout(timer)
    // Cut any flight short where the camera is
    const { lng, lat, height } = v.camera.positionGeographic
    v.setCamera({ lng, lat, height, ...v.camera.orientation })
  }
  tour()
})

onBeforeUnmount(() => {
  setTouring = undefined
  clearTimeout(timer)
  clearTimeout(labelTimer)
  view?.dispose()
  view = undefined
})
</script>

<template>
  <div class="map-canvas day04">
    <div ref="container" class="map-canvas" />
    <button type="button" class="tour" :aria-pressed="touring" @click="setTouring?.(!touring)">
      {{ touring ? '❚❚ Stop tour' : '▶ Play tour' }}
    </button>
  </div>
</template>


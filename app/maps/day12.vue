<script setup lang="ts">
// Day 12: Power — the power of the world's ocean waves, from ECMWF's wave model, two ways (a
// button switches): as a fluid, a Navier-Stokes simulation pulled along the way the waves go (the
// longer the period, the faster), stirring dye in the color of how much power the waves carry; or
// as streamlines, crests running the way the waves go and leaving a wake of their energy. The
// more power, the lighter: navy in the calms to white under the storms; both worked out over
// what's in view. With ?gui=1, a panel (lil-gui) tunes them as they run
import ThreeView, { Color } from '@navaramap/three'
import { DefaultPlugin, type DefaultDescriptions } from '@navaramap/three-default-plugin'
import { TileJsonPlugin } from '@navaramap/three-plugins'
import GUI, { type Controller } from 'lil-gui'
import { LimbGlowMeshDesc, type LimbGlowConfig } from './lib/LimbGlowMeshDesc'
import { StarfieldMeshDesc, type StarfieldConfig } from './lib/StarfieldMeshDesc'
import { WaveFluidMeshDesc, type WaveFluidConfig } from './lib/WaveFluidMeshDesc'
import { WaveStreamMeshDesc, type WaveStreamConfig } from './lib/WaveStreamMeshDesc'
import { PHASE_SPEED, type WaveGrid } from './lib/waveField'

// Generated by scripts/day12/fetch_waves.py
const dataBase = `${useRuntimeConfig().app.baseURL}data/day12`

const NIGHT = '#03060f'
const LAND_TINT = new Color().setStyle('#5d6680')

// The North Pacific, from Japan out to the storm south of the Aleutians
const START = { lng: -178, lat: 38, height: 0, distance: 11_000_000, heading: 0, pitch: -90, roll: 0 }
// No lower than this (m), well above the shell over the sea. (Held here: the camera's
// minimumZoomDistance doesn't stop the wheel in Navara 0.3.1)
const MIN_HEIGHT = 300_000
const BLOOM = 0.6

const MODES = { fluid: 'Fluid', stream: 'Streamlines' } as const
type Mode = keyof typeof MODES

const container = ref<HTMLDivElement>()
const controls = ref<HTMLDivElement>()
const mode = ref<Mode>('fluid')
let view: ThreeView<DefaultDescriptions> | undefined
let gui: GUI | undefined

onMounted(async () => {
  const [meta, data] = await Promise.all([
    fetch(`${dataBase}/waves.json`).then((r) => r.json()),
    fetch(`${dataBase}/waves.bin`).then((r) => r.arrayBuffer()),
  ])
  if (!container.value) return // unmounted while loading
  const grid: WaveGrid = { ...meta, data: new Uint16Array(data) }

  const v = new ThreeView<DefaultDescriptions>({
    container: container.value,
    backgroundColor: new Color().setStyle(NIGHT),
    animation: true,
  })
  view = v
  v.addPlugin(new DefaultPlugin())
  const tilejson = new TileJsonPlugin()
  v.addPlugin(tilejson)
  await v.init()
  if (view !== v) return // unmounted while initializing
  v.registerMesh('limbGlow', LimbGlowMeshDesc)
  v.registerMesh('starfield', StarfieldMeshDesc)
  v.registerMesh('waveFluid', WaveFluidMeshDesc)
  v.registerMesh('waveStream', WaveStreamMeshDesc)

  v.globe.color = new Color().setStyle(NIGHT)
  v.setCamera(START)
  const bloom = v.addEffect({ selectiveBloom: { strength: BLOOM, radius: 0.5, threshold: 0 } })

  // (typed separately: the view's mesh config union only knows the DefaultPlugin descriptors)
  const limbGlow: LimbGlowConfig = { limbGlow: { color: new Color().setStyle('#3f8cff'), intensity: 0.7, scaleHeight: 80_000 } }
  v.addMesh<LimbGlowMeshDesc>(limbGlow)
  const starfield: StarfieldConfig = { starfield: {} }
  v.addMesh<StarfieldMeshDesc>(starfield)

  const basemap = await tilejson.addSource({
    type: 'raster-tile',
    url: 'https://papers.reearth.land/styles/papers-dark/tilejson.json',
  })
  v.addLayer({ type: 'raster', source: basemap, raster: { color: LAND_TINT } })

  // Both looks, only the one shown running; it starts afresh when switched to
  const fluidConfig: WaveFluidConfig = { effectIds: [bloom.id], waveFluid: { grid } }
  const streamConfig: WaveStreamConfig = { effectIds: [bloom.id], waveStream: { grid } }
  const looks = {
    fluid: v.addMesh<WaveFluidMeshDesc>(fluidConfig),
    stream: v.addMesh<WaveStreamMeshDesc>(streamConfig),
  }
  const show = (m: Mode) => {
    for (const [key, look] of Object.entries(looks)) look.visible = key === m
    looks[m].ref.reset()
  }
  show(mode.value)
  watch(mode, show)

  // The panel, only with ?gui=1: what both share, then the look shown's own, each with a line on
  // what it does
  if (useRoute().query.gui === '1') {
    gui = new GUI({ container: controls.value, title: 'Parameters', width: 300 })
    const hint = (c: Controller, text: string) => {
      const el = document.createElement('div')
      el.className = 'hint'
      el.textContent = text
      c.domElement.classList.add('has-hint')
      c.domElement.append(el)
      return c
    }
    const shared = { speed: PHASE_SPEED, bloom: BLOOM }
    const both = gui.addFolder('Waves')
    const speed = both.add(shared, 'speed', 0.005, 0.2, 0.005).name('crest speed')
    speed.onChange((x: number) => {
      looks.fluid.ref.speed = looks.stream.ref.speed = x
    })
    hint(speed, '波の峰が進む速さ（両モード）。インク・航跡はその半分で流れる')
    // (the handle's update is typed for any effect; the bloom's own config type isn't exported)
    const bloomHandle = bloom as unknown as { update(u: { selectiveBloom: { strength: number } }): void }
    hint(
      both.add(shared, 'bloom', 0, 2, 0.05).onChange((x: number) => bloomHandle.update({ selectiveBloom: { strength: x } })),
      '明るいところの光のにじみ',
    )
    const fluid = gui.addFolder('Fluid')
    const f = looks.fluid.ref.params
    hint(fluid.add(f, 'stir', 0, 100, 1), '荒れた海で渦を起こす力。上げると渦が強く大きくなる')
    hint(fluid.add(f, 'pull', 0.1, 5, 0.1), '渦がかき混ぜの力に追いつく速さ。上げると反応が早い')
    hint(fluid.add(f, 'curl', 0, 50, 1).name('curl (confinement)'), '小さな渦を増幅する。上げると細かい巻き込みが増える')
    hint(
      fluid.add(f, 'pressureIterations', 1, 60, 1).name('pressure iterations'),
      '圧力計算の反復回数。下げると軽いが、渦の形が崩れる',
    )
    hint(fluid.add(f, 'velocityDissipation', 0, 1, 0.01).name('eddy dissipation'), '渦の減衰。上げると渦がすぐ消える')
    hint(fluid.add(f, 'relax', 0.05, 2, 0.05).name('dye relax'), 'インクがその場の色に戻る速さ。下げると色が遠くまで流れる')
    hint(fluid.add(f, 'plumes', 0, 4, 0.05), '斑の中で余分に足すインク。上げると濃淡の帯がくっきりする')
    hint(fluid.add(f, 'flatness', 0.01, 0.3, 0.005).name('relief flatness'), '陰影の起伏。下げるほど凹凸が深くなる')
    hint(fluid.add(f, 'light', 0, 1.5, 0.05), '光の当たる面の明るさ')
    hint(fluid.add(f, 'glint', 0, 1, 0.05), '水面の照り返しの強さ')
    const stream = gui.addFolder('Streamlines')
    const st = looks.stream.ref.params
    hint(stream.add(st, 'fade', 0.2, 6, 0.1).name('wake fade (s)'), '航跡が薄れるまでの時間。上げると筋が長くなる')
    hint(stream.add(st, 'lifeMin', 0.5, 10, 0.5).name('life min (s)'), '峰が生まれ変わるまでの寿命（最短）')
    hint(stream.add(st, 'lifeMax', 0.5, 15, 0.5).name('life max (s)'), '峰が生まれ変わるまでの寿命（最長）')
    hint(stream.add(st, 'brightness', 0.005, 0.2, 0.005), '峰 1 つが航跡に足す明るさ')
    hint(stream.add(st, 'pointSize', 1, 4, 0.25).name('crest size'), '峰の点の大きさ。上げると筋が太くなる')
    hint(stream.add(st, 'glow', 0, 2, 0.05), '嵐の海域での航跡の明るさ')
    const showFolders = (m: Mode) => {
      fluid.show(m === 'fluid')
      stream.show(m === 'stream')
    }
    showFolders(mode.value)
    watch(mode, showFolders)
    // Back to the defaults: every controller to where it started
    hint(gui.add({ reset: () => gui?.reset() }, 'reset'), 'すべて既定値に戻す')
  }

  let last = performance.now()
  v.on('preUpdate', () => {
    const now = performance.now()
    const at = v.camera.positionGeographic
    if (at.height < MIN_HEIGHT) v.setCamera({ ...at, ...v.camera.orientation, height: MIN_HEIGHT })
    looks[mode.value].ref.step((now - last) / 1000, v.camera.raw)
    last = now
  })

  v.attribution?.add([
    {
      attributionHtml: `Waves: <a href="https://www.ecmwf.int/en/forecasts/datasets/open-data">ECMWF open data</a> (IFS wave model, ${meta.time.replace('T', ' ').replace('Z', ' UTC')}), CC BY 4.0`,
    },
  ])
})

onBeforeUnmount(() => {
  gui?.destroy()
  gui = undefined
  view?.dispose()
  view = undefined
})
</script>

<template>
  <div class="map-canvas day12">
    <div ref="container" class="map-canvas" />
    <div ref="controls" class="controls" />
    <div class="modes" role="group" aria-label="Look">
      <button v-for="(label, key) in MODES" :key="key" type="button" :aria-pressed="mode === key" @click="mode = key">
        {{ label }}
      </button>
    </div>
  </div>
</template>


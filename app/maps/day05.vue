<script setup lang="ts">
// Day 5: Senses: Sight — Tokyo Skytree lit up at night (PLATEAU LOD3). The camera flies in from
// 3 km out, lands at the tower's foot and looks up it, following a band of light to the top,
// rises past the decks, looks down from above the antenna, then pulls back out
import ThreeView, { Color } from '@navaramap/three'
import { DefaultPlugin, type DefaultDescriptions } from '@navaramap/three-default-plugin'
import { TileJsonPlugin } from '@navaramap/three-plugins'
import { SkytreeLedsMeshDesc, type SkytreeLedsConfig } from './lib/SkytreeLedsMeshDesc'
import { StarfieldMeshDesc, type StarfieldConfig } from './lib/StarfieldMeshDesc'

// Generated by scripts/day05/extract_skytree.py
const baseURL = useRuntimeConfig().app.baseURL
const dataBase = `${baseURL}data/day05`

// PLATEAU 2025 Sumida-ku buildings, LOD3 with textures
const SUMIDA_LOD3 =
  'https://assets.cms.plateau.reearth.io/assets/f2/aaaf35-d94c-4c15-affd-d9f652cd16c1/13107_sumida-ku_pref_2025_citygml_1_op_bldg_3dtiles_13107_sumida-ku_lod3/tileset.json'
// PLATEAU heights are ellipsoidal and the basemap lies on the ellipsoid: drop the buildings
// by the geoid height at Oshiage so they stand on it
const GEOID_M = 36.7

const NIGHT = '#060b1c'
// Skytree's two lightings, alternating: Iki (粋), the pale blue of the Sumida River, and
// Miyabi (雅), Edo purple
const LIGHTINGS = [
  { name: 'Iki 粋', color: new Color().setStyle('#8fd8ff') },
  { name: 'Miyabi 雅', color: new Color().setStyle('#b689ff') },
]

// The tour, as keyframes around the tower's axis, one round after another:
// t (s into the round), bearing of the eye from the axis (deg), its distance from the axis and
// height (m), and the height on the axis it looks at (m). Each round starts ROUND_TURN further
// round, so every fly-in comes from another side; the first comes from Asakusa, across the
// Sumida River. Distance and height ease in log space, so the fly-in slows as it closes in
type Key = { t: number; bearing: number; dist: number; height: number; look: number }
const KEYS: Key[] = [
  { t: 0, bearing: 250, dist: 3000, height: 220, look: 330 }, // 3 km out, over Asakusa
  { t: 5, bearing: 250, dist: 2500, height: 210, look: 330 },
  { t: 10, bearing: 245, dist: 1100, height: 150, look: 320 },
  { t: 14, bearing: 235, dist: 320, height: 85, look: 280 },
  { t: 17, bearing: 222, dist: 90, height: 55, look: 170 },
  { t: 20, bearing: 210, dist: 55, height: 48, look: 110 }, // at the foot, over the complex's roof
  { t: 25, bearing: 185, dist: 55, height: 48, look: 380 },
  { t: 30, bearing: 160, dist: 55, height: 48, look: 634 }, // looking straight up the tower
  { t: 33, bearing: 145, dist: 90, height: 330, look: 720 },
  { t: 37, bearing: 130, dist: 85, height: 820, look: 300 },
  { t: 40, bearing: 120, dist: 70, height: 950, look: 0 }, // above the antenna, looking down
  { t: 45, bearing: 115, dist: 1800, height: 320, look: 330 },
]
const ROUND_S = 50
const ROUND_TURN = -140
// Phases, in s into the round
const CLIMB = { from: 19, to: 31 } // the band of light rides the gaze up
const WIPE = { from: 34, to: 41 } // the next lighting paints the tower from the top down

type Leds = { origin: { lng: number; lat: number; height: number }; top: number; points: number[] }

const container = ref<HTMLDivElement>()
let view: ThreeView<DefaultDescriptions> | undefined

// The camera tour, with a button to stop and restart it
const touring = ref(true)
const lighting = ref(LIGHTINGS[0]!.name)
let setTouring: ((on: boolean) => void) | undefined

// The i-th key of the endless tour, rounds after the first shifted round the tower
function key(i: number): Key {
  const round = Math.floor(i / KEYS.length)
  const k = KEYS[i - round * KEYS.length]!
  return { ...k, t: k.t + round * ROUND_S, bearing: k.bearing + round * ROUND_TURN }
}

// Cubic Hermite through the keys, with Catmull-Rom tangents scaled by the keys' spacing in time
function sample(time: number): Key {
  const round = Math.floor(time / ROUND_S)
  let i = round * KEYS.length
  while (key(i + 1).t <= time) i++
  const [k0, k1, k2, k3] = [key(i - 1), key(i), key(i + 1), key(i + 2)]
  const dt = k2.t - k1.t
  const u = (time - k1.t) / dt
  const h00 = 2 * u ** 3 - 3 * u ** 2 + 1
  const h10 = u ** 3 - 2 * u ** 2 + u
  const h01 = -2 * u ** 3 + 3 * u ** 2
  const h11 = u ** 3 - u ** 2
  const lerp = (f: (k: Key) => number) => {
    const m1 = ((f(k2) - f(k0)) / (k2.t - k0.t)) * dt
    const m2 = ((f(k3) - f(k1)) / (k3.t - k1.t)) * dt
    return h00 * f(k1) + h10 * m1 + h01 * f(k2) + h11 * m2
  }
  return {
    t: time,
    bearing: lerp((k) => k.bearing),
    dist: Math.exp(lerp((k) => Math.log(k.dist))),
    height: Math.exp(lerp((k) => Math.log(k.height))),
    look: lerp((k) => k.look),
  }
}

const smooth = (x: number) => (x <= 0 ? 0 : x >= 1 ? 1 : x * x * (3 - 2 * x))

onMounted(async () => {
  const v = new ThreeView<DefaultDescriptions>({
    container: container.value!,
    backgroundColor: new Color().setStyle(NIGHT),
    animation: true,
  })
  view = v
  v.addPlugin(new DefaultPlugin())
  const tilejson = new TileJsonPlugin()
  v.addPlugin(tilejson)
  const [leds] = await Promise.all([fetch(`${dataBase}/skytree_leds.json`).then((r) => r.json() as Promise<Leds>), v.init()])
  if (view !== v) return // unmounted while initializing
  v.registerMesh('starfield', StarfieldMeshDesc)
  v.registerMesh('skytreeLeds', SkytreeLedsMeshDesc)

  // A tour pose -> the camera, facing the axis
  const { lng, lat } = leds.origin
  const mPerLng = 111_320 * Math.cos((lat * Math.PI) / 180)
  const cameraAt = (k: Key) => {
    const b = (k.bearing * Math.PI) / 180
    return {
      lng: lng + (k.dist * Math.sin(b)) / mPerLng,
      lat: lat + (k.dist * Math.cos(b)) / 110_950,
      height: k.height,
      heading: k.bearing + 180,
      pitch: (Math.atan2(k.look - k.height, k.dist) * 180) / Math.PI,
      roll: 0,
    }
  }
  v.setCamera(cameraAt(sample(0)))

  // (typed separately: the view's mesh config union only knows the DefaultPlugin descriptors)
  const starfield: StarfieldConfig = { starfield: {} }
  v.addMesh<StarfieldMeshDesc>(starfield)
  // Just enough light to make out the town around the tower
  v.addLight({ ambient: { color: new Color().setStyle('#8ea2ff'), intensity: 0.25 } })
  const bloom = v.addEffect({ selectiveBloom: { strength: 1.4, radius: 0.5, threshold: 0 } })

  // The dark sibling of the basemap Navara's own examples use (Re:Earth Papers); the plugin credits it from the TileJSON
  const basemap = await tilejson.addSource({
    type: 'raster-tile',
    url: 'https://papers.reearth.land/styles/papers-dark/tilejson.json',
  })
  if (view !== v) return
  v.addLayer({ type: 'raster', source: basemap })

  // The town, the tower included, stays dark: the tower's feature also holds the Tokyo Solamachi
  // complex at its foot, so a glow on it would light the complex as well. The LEDs light it instead
  const tiles = v.addSource({ type: '3d-tiles', url: SUMIDA_LOD3 })
  v.addLayer({ type: '3d-tiles', source: tiles, model: { height: -GEOID_M } })

  const ledsConfig: SkytreeLedsConfig = {
    effectIds: [bloom.id],
    geodetic: { ...leds.origin, height: leds.origin.height - GEOID_M },
    skytreeLeds: { points: Float32Array.from(leds.points, (d) => d / 10), color: LIGHTINGS[0]!.color },
  }
  const ledsMesh = v.addMesh<SkytreeLedsMeshDesc>(ledsConfig)

  v.attribution?.add([
    {
      attributionHtml: '3D city model: <a href="https://www.mlit.go.jp/plateau/">PLATEAU</a> (MLIT)',
    },
  ])

  // Tour time (s) runs only while touring; `clock` maps performance.now() onto it
  let clock: number | undefined
  let tourTime = 0
  let lit = 0 // lightings shown so far: the current one is lit % LIGHTINGS.length
  const lightingAt = (i: number) => LIGHTINGS[i % LIGHTINGS.length]!
  v.on('preUpdate', () => {
    const now = performance.now()
    let sweep = -1
    let wipe: number | undefined
    if (clock !== undefined) {
      tourTime = (now - clock) / 1000
      const k = sample(tourTime)
      v.setCamera(cameraAt(k))
      const t = tourTime % ROUND_S
      const round = Math.floor(tourTime / ROUND_S)
      if (t >= CLIMB.from && t < CLIMB.to) sweep = Math.max(k.look, 0)

      // The wipe repaints from just above the top to just below the foot; the round's lighting
      // is lit when it ends
      const next = round + 1
      if (t >= WIPE.from && t < WIPE.to) {
        if (lit !== round) lit = round // a resumed tour catches up
        ledsMesh.ref.setColors(lightingAt(lit).color, lightingAt(next).color)
        lighting.value = lightingAt(next).name
        wipe = leds.top + 30 - smooth((t - WIPE.from) / (WIPE.to - WIPE.from)) * (leds.top + 60)
      } else if (t >= WIPE.to && lit !== next) {
        lit = next
        ledsMesh.ref.setColors(lightingAt(lit).color, lightingAt(lit).color)
        lighting.value = lightingAt(lit).name
      }
    }
    ledsMesh.ref.tick(now / 1000, sweep, wipe)
  })

  // Grabbing the camera stops the tour and hands it over
  const grab = () => touring.value && setTouring?.(false)
  for (const type of ['pointerdown', 'wheel', 'touchstart'] as const) {
    container.value?.addEventListener(type, grab, { passive: true })
  }

  setTouring = (on) => {
    touring.value = on
    if (!on) {
      clock = undefined
      return
    }
    // Resume at the start of the next round: fly there, then let the clock run
    const resumeAt = Math.ceil(tourTime / ROUND_S) * ROUND_S
    v.flyTo(cameraAt(sample(resumeAt)), { duration: 3000, easing: 'cubicInOut' }).then((ok) => {
      if (ok && touring.value && view === v) clock = performance.now() - resumeAt * 1000
    })
  }
  clock = performance.now()
})

onBeforeUnmount(() => {
  setTouring = undefined
  view?.dispose()
  view = undefined
})
</script>

<template>
  <div class="map-canvas day05">
    <div ref="container" class="map-canvas" />
    <div class="controls">
      <span class="chip">{{ lighting }}</span>
      <button type="button" class="chip tour" :aria-pressed="touring" @click="setTouring?.(!touring)">
        {{ touring ? '❚❚ Stop tour' : '▶ Play tour' }}
      </button>
    </div>
  </div>
</template>


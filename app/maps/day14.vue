<script setup lang="ts">
// Day 14: Borgesian map — Mt. Fuji, from the map down to the ground itself. GSI's standard map
// seen from straight above turns into the aerial photo, the mountain rises out of it, the
// summit sharpens into VIRTUAL SHIZUOKA's 20 cm photo while the rest of the mountain sinks
// away, and the camera goes down into the crater, where snow falls and settles on the ground
import ThreeView, { Color, JAPAN_GSI_ELEVATION_DECODER } from '@navaramap/three'
import { DefaultPlugin, type DefaultDescriptions } from '@navaramap/three-default-plugin'
import { Color as ThreeColor, TextureLoader } from 'three'
import { CloudDeckMeshDesc, type CloudDeckConfig } from './lib/CloudDeckMeshDesc'
import { CraterSurfaceMeshDesc, type CraterSurfaceConfig } from './lib/CraterSurfaceMeshDesc'
import { SkyDomeMeshDesc, type SkyDomeConfig } from './lib/SkyDomeMeshDesc'
import { SnowfallMeshDesc, type SnowfallConfig } from './lib/SnowfallMeshDesc'

// Generated by scripts/day14/extract_crater.py
const baseURL = useRuntimeConfig().app.baseURL
const dataBase = `${baseURL}data/day14`

const GSI = 'https://cyberjapandata.gsi.go.jp/xyz'

// The tour, as keyframes round the crater's centre: t (s into the round), bearing of the eye
// from the centre (deg), its distance from it (m), its height above sea level (m) and its pitch
// (deg, up positive). Distance and height ease in log space
type Key = { t: number; bearing: number; dist: number; height: number; pitch: number }
const KEYS: Key[] = [
  { t: 0, bearing: 180, dist: 1, height: 42000, pitch: -90 }, // the standard map, straight down
  { t: 14, bearing: 180, dist: 1, height: 40000, pitch: -90 },
  { t: 20, bearing: 182, dist: 400, height: 30000, pitch: -86 }, // the photo
  { t: 30, bearing: 200, dist: 14000, height: 9500, pitch: -22 }, // the mountain risen
  { t: 38, bearing: 215, dist: 3200, height: 5200, pitch: -28 },
  { t: 45, bearing: 225, dist: 1100, height: 4300, pitch: -30 }, // over the crater
  { t: 52, bearing: 235, dist: 420, height: 3830, pitch: -14 }, // over the rim
  { t: 59, bearing: 240, dist: 110, height: 3600, pitch: 2 }, // down in the crater, ~25 m up
  { t: 69, bearing: 270, dist: 60, height: 3572, pitch: 16 },
  { t: 80, bearing: 320, dist: 40, height: 3562, pitch: 26 },
  { t: 92, bearing: 370, dist: 30, height: 3558, pitch: 34 },
]
const ROUND_S = 92
// How fast the tour runs: the keyframes and phases are in s of tour, this many per s of the clock
const SPEED = 2

// Phases, in s into the round: [from, to]
const PHOTO = [14, 19] // the standard map fades into the photo
const RISE = [20, 29] // the terrain rises out of the flat map
const ASSEMBLE = [33, 39] // the summit's photo comes in from the crater floor out
const SINK = [41, 50] // the rest of the mountain sinks away, leaving the summit's ground
const STORM = [50, 64] // the sky closes in and the snow starts
const SETTLE = [55, 88] // snow settles on the ground
const WHITEOUT = [87, 91] // the snow fills the view; the round starts again from white

const SKY = {
  day: { horizon: new ThreeColor('#d4dde6'), zenith: new ThreeColor('#7fa5cf') },
  storm: { horizon: new ThreeColor('#7c8794'), zenith: new ThreeColor('#3d4653') },
}

// Navara caps a phone's pixel ratio at 2, which leaves a 3x screen soft. Render at the screen's own
// ratio (up to 3); the point and snow shaders size their sprites with the same number
// A touch screen, or a narrow one (Navara's own test for a phone)
const IS_PHONE = matchMedia('(pointer: coarse)').matches || window.innerWidth <= 768
const PIXEL_RATIO = Math.min(window.devicePixelRatio || 1, 3)

const route = useRoute()
const container = ref<HTMLDivElement>()
const whiteout = ref(1)
const touring = ref(true)
let view: ThreeView<DefaultDescriptions> | undefined
let setTouring: ((on: boolean) => void) | undefined

// Cubic Hermite through the keys, with Catmull-Rom tangents scaled by the keys' spacing in time
function sample(time: number): Key {
  const t = ((time % ROUND_S) + ROUND_S) % ROUND_S
  let i = 0
  while (i < KEYS.length - 2 && KEYS[i + 1]!.t <= t) i++
  const k = (j: number) => KEYS[Math.min(Math.max(j, 0), KEYS.length - 1)]!
  const [k0, k1, k2, k3] = [k(i - 1), k(i), k(i + 1), k(i + 2)]
  const dt = k2.t - k1.t
  const u = Math.min((t - k1.t) / dt, 1)
  const h00 = 2 * u ** 3 - 3 * u ** 2 + 1
  const h10 = u ** 3 - 2 * u ** 2 + u
  const h01 = -2 * u ** 3 + 3 * u ** 2
  const h11 = u ** 3 - u ** 2
  const lerp = (f: (k: Key) => number) => {
    const m1 = k0 === k1 ? 0 : ((f(k2) - f(k0)) / (k2.t - k0.t)) * dt
    const m2 = k3 === k2 ? 0 : ((f(k3) - f(k1)) / (k3.t - k1.t)) * dt
    return h00 * f(k1) + h10 * m1 + h01 * f(k2) + h11 * m2
  }
  return {
    t,
    bearing: lerp((k) => k.bearing),
    dist: Math.exp(lerp((k) => Math.log(k.dist))),
    height: Math.exp(lerp((k) => Math.log(k.height))),
    pitch: lerp((k) => k.pitch),
  }
}

const smooth = (x: number) => (x <= 0 ? 0 : x >= 1 ? 1 : x * x * (3 - 2 * x))
/** 0 before the phase, 1 after it, easing in between */
const phase = (t: number, [from, to]: number[]) => smooth((t - from!) / (to! - from!))

type Crater = {
  origin: { lng: number; lat: number; height: number }
  surface: { cols: number; rows: number }
}

async function loadCrater() {
  const [meta, surface, photo] = await Promise.all([
    fetch(`${dataBase}/crater.json`).then((r) => r.json() as Promise<Crater>),
    fetch(`${dataBase}/crater_surface.bin`).then((r) => r.arrayBuffer()),
    new TextureLoader().loadAsync(`${dataBase}/crater_ortho.jpg`),
  ])
  const vertices = Float32Array.from(new Int16Array(surface), (d) => d / 10)
  return { meta, vertices, photo }
}

onMounted(async () => {
  const v = new ThreeView<DefaultDescriptions>({
    container: container.value!,
    backgroundColor: new Color().setStyle('#d4dde6'),
    animation: true,
    pixelRatio: PIXEL_RATIO,
    // A phone's defaults keep the tiles coarser than on a desktop: LOD fog (sseFactor 6-12 against
    // 2) and a resting memory-pressure multiplier on the screen-space error (4-8 against 1). This
    // map is looked at from far up, where that's a level or two of blur, so use the desktop's. The
    // multiplier still rises to 4 if the memory runs short
    lodFog: { enabled: true, density: 2e-4, sseFactor: 2 },
    memoryBudget: { sseMultiplierMin: 1, sseMultiplierMax: 4 },
    // Tiles are refined until their error is under this many pixels (default 2). On a desktop, half
    // a pixel: a zoom level deeper, as the standard map's 256 px tiles are otherwise stretched on
    // a high-density screen. A phone is sharp enough at 1, and has less to spare
    maxSse: IS_PHONE ? 1 : 0.5,
  })
  view = v
  v.addPlugin(new DefaultPlugin())
  const crater = loadCrater()
  await v.init()
  if (view !== v) return // unmounted while initializing
  v.registerMesh('skyDome', SkyDomeMeshDesc)
  v.registerMesh('cloudDeck', CloudDeckMeshDesc)
  v.registerMesh('craterSurface', CraterSurfaceMeshDesc)
  v.registerMesh('snowfall', SnowfallMeshDesc)

  // The crater's centre, until its data says exactly where (scripts/day14/extract_crater.py)
  const origin = { lng: 138.7306477, lat: 35.3626903, height: 3537.59 }
  const mPerLng = 111_320 * Math.cos((origin.lat * Math.PI) / 180)
  const cameraAt = (k: Key) => {
    const b = (k.bearing * Math.PI) / 180
    return {
      lng: origin.lng + (k.dist * Math.sin(b)) / mPerLng,
      lat: origin.lat + (k.dist * Math.cos(b)) / 110_950,
      height: k.height,
      heading: k.bearing + 180,
      pitch: k.pitch,
      roll: 0,
    }
  }
  v.setCamera(cameraAt(sample(0)))

  const skyConfig: SkyDomeConfig = { skyDome: {}, geodetic: origin }
  const sky = v.addMesh<SkyDomeMeshDesc>(skyConfig)
  const deckConfig: CloudDeckConfig = { cloudDeck: {}, geodetic: origin }
  const deck = v.addMesh<CloudDeckMeshDesc>(deckConfig)
  v.addLight({ ambient: { intensity: 1.0 } })

  // GSI's DEM under its standard map and its photo, the map on top
  const dem = v.addSource({
    type: 'raster-dem',
    url: `${GSI}/dem_png/{z}/{x}/{y}.png`,
    elevationDecoder: JAPAN_GSI_ELEVATION_DECODER(),
    tileSize: 256,
    maxZoom: 14,
  })
  const terrain = v.addLayer({ type: 'terrain', source: dem, terrain: { exaggeration: 0 } })
  const photo = v.addSource({ type: 'raster-tile', url: `${GSI}/seamlessphoto/{z}/{x}/{y}.jpg`, maxZoom: 18 })
  const photoLayer = v.addLayer({ type: 'raster', source: photo, raster: { show: true } })
  const std = v.addSource({ type: 'raster-tile', url: `${GSI}/std/{z}/{x}/{y}.png`, maxZoom: 18 })
  const stdLayer = v.addLayer({ type: 'raster', source: std, raster: { opacity: 1 } })

  v.attribution?.add([
    { attributionHtml: '<a href="https://maps.gsi.go.jp/development/ichiran.html">出典：国土地理院</a>' },
    {
      attributionHtml:
        'Ortho &amp; DEM: <a href="https://github.com/aigidjp/opendata_virtualshizuoka">VIRTUAL SHIZUOKA</a> (Shizuoka Prefecture, CC BY 4.0)',
    },
  ])

  // The crater's meshes, once its data is in
  let surface: ReturnType<typeof v.addMesh<CraterSurfaceMeshDesc>> | undefined
  let snowFar: ReturnType<typeof v.addMesh<SnowfallMeshDesc>> | undefined
  let snowNear: ReturnType<typeof v.addMesh<SnowfallMeshDesc>> | undefined
  crater.then((c) => {
    if (view !== v) return
    const geodetic = c.meta.origin
    const surfaceConfig: CraterSurfaceConfig = {
      geodetic,
      craterSurface: { vertices: c.vertices, ...c.meta.surface, photo: c.photo },
    }
    surface = v.addMesh<CraterSurfaceMeshDesc>(surfaceConfig)
    // Snow over the whole crater, and a box of it round the camera for the flakes close by
    const farConfig: SnowfallConfig = { geodetic, snowfall: { count: 220_000 } }
    snowFar = v.addMesh<SnowfallMeshDesc>(farConfig)
    const nearConfig: SnowfallConfig = { geodetic, snowfall: { count: 60_000, width: 60, height: 60, followCamera: true, far: 50 } }
    snowNear = v.addMesh<SnowfallMeshDesc>(nearConfig)
  })

  // Layer updates go through the engine: only send them when they change
  let lastOpacity = -1
  let lastExaggeration = -1
  const horizon = new ThreeColor()
  const zenith = new ThreeColor()

  let clock: number | undefined
  let tourTime = 0
  v.on('preUpdate', () => {
    const now = performance.now()
    if (clock !== undefined) {
      tourTime = ((now - clock) / 1000) * SPEED
      v.setCamera(cameraAt(sample(tourTime)))
    }
    const t = ((tourTime % ROUND_S) + ROUND_S) % ROUND_S

    const opacity = Math.round((1 - phase(t, PHOTO)) * 100) / 100
    if (opacity !== lastOpacity) {
      stdLayer.update({ type: 'raster', source: std, raster: { opacity, show: opacity > 0 } })
      lastOpacity = opacity
    }
    // Rises from flat, settles a few metres low under the summit's own surface, then sinks away
    const exaggeration =
      Math.round((phase(t, RISE) - 0.002 * phase(t, ASSEMBLE) - 0.998 * phase(t, SINK)) * 1000) / 1000
    if (exaggeration !== lastExaggeration) {
      // Sunk all the way, the mountain and its photo are gone
      const show = exaggeration > 0 || t < RISE[1]!
      terrain.update({ type: 'terrain', source: dem, terrain: { exaggeration, show } })
      photoLayer.update({ type: 'raster', source: photo, raster: { show } })
      lastExaggeration = exaggeration
    }

    // The front runs from the crater floor (0) past the survey's edges (~1.2)
    const front = (p: number) => -0.2 + 1.5 * p
    const storm = phase(t, STORM)
    const light = 1 - 0.3 * storm
    surface?.ref.setFront(front(phase(t, ASSEMBLE)), -1)
    surface?.ref.setSnow(phase(t, SETTLE), light)
    snowFar?.ref.tick(now / 1000, storm, light)
    snowNear?.ref.tick(now / 1000, storm * phase(t, [52, 60]), light)

    horizon.lerpColors(SKY.day.horizon, SKY.storm.horizon, storm)
    zenith.lerpColors(SKY.day.zenith, SKY.storm.zenith, storm)
    sky.ref.setColors(horizon, zenith)
    // The sea of clouds rises from sea level to ~350 m under the crater floor as the mountain sinks
    const sink = phase(t, SINK)
    deck.ref.set(-origin.height + (origin.height - 350) * sink, horizon, sink > 0)

    // From white into the map, and into white at the end of the round
    whiteout.value = Math.max(1 - phase(t, [0, 2.5]), phase(t, WHITEOUT))
  })

  // Grabbing the camera stops the tour and hands it over
  const grab = () => touring.value && setTouring?.(false)
  for (const type of ['pointerdown', 'wheel', 'touchstart'] as const) {
    container.value?.addEventListener(type, grab, { passive: true })
  }

  setTouring = (on) => {
    touring.value = on
    if (!on) {
      clock = undefined
      return
    }
    // Resume where the tour stopped: fly back there, then let the clock run
    const resumeAt = tourTime
    v.flyTo(cameraAt(sample(resumeAt)), { duration: 3000, easing: 'cubicInOut' }).then((ok) => {
      if (ok && touring.value && view === v) clock = performance.now() - (resumeAt / SPEED) * 1000
    })
  }
  // ?t=<s> starts the tour that far in, for tuning a phase without waiting for it
  const startAt = Number(route.query.t) || 0
  clock = performance.now() - (startAt / SPEED) * 1000
})

onBeforeUnmount(() => {
  setTouring = undefined
  view?.dispose()
  view = undefined
})
</script>

<template>
  <div class="map-canvas day14">
    <div ref="container" class="map-canvas" />
    <div class="whiteout" :style="{ opacity: whiteout }" />
    <div class="controls">
      <button type="button" class="chip tour" :aria-pressed="touring" @click="setTouring?.(!touring)">
        {{ touring ? '❚❚ Stop tour' : '▶ Play tour' }}
      </button>
    </div>
  </div>
</template>


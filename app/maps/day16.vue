<script setup lang="ts">
// Day 16: Collaborative map — the map I meant to make with the runners next to me at the Kobe
// Marathon, asking each "Where are you from?" as we ran. I never found the nerve, so this is
// the impression instead, told in 20 seconds (lib/whereFrom.ts): on the course I ran (from my
// watch's GPS), the field strings out from the start, me among them in white; I ask, the
// runners around me answer, and their homes show on the map and a minimap, one by one, then
// faster and faster, until the punchline. Then the camera pulls back to the globe as arcs grow
// from every home to Kobe: mostly Kobe itself, then Hyogo and Osaka, out to Sapporo and Naha,
// Taiwan, Korea, the Philippines, Indonesia, Australia, India, Europe and America, a runner
// racing down each. The photos I took on the way stand on the course; grab the camera to look
// around
import ThreeView, { Color, geodeticToVector3 } from '@navaramap/three'
import { DefaultPlugin, type DefaultDescriptions } from '@navaramap/three-default-plugin'
import { ArcGlowMeshDesc, type ArcGlowConfig } from './lib/ArcGlowMeshDesc'
import { CourseFlowMeshDesc, type CourseFlowConfig } from './lib/CourseFlowMeshDesc'
import { KOBE } from './lib/kobeRunners'
import { LimbGlowMeshDesc, type LimbGlowConfig } from './lib/LimbGlowMeshDesc'
import { StarfieldMeshDesc, type StarfieldConfig } from './lib/StarfieldMeshDesc'
import { PULL_BACK, WhereFrom, type Homes } from './lib/whereFrom'
import { Vector3 } from 'three'

const baseURL = useRuntimeConfig().app.baseURL
// Generated by scripts/day16/extract_course.py, scatter_homes.py and prepare_photo.py
const dataBase = `${baseURL}data/day16`
// OSM Japan's Toner (English labels), rendered: white land, black sea, black labels
const TONER_HOST = 'https://tile.openstreetmap.jp/styles/maptiler-toner-en'
const TONER = `${TONER_HOST}/{z}/{x}/{y}.png`

const NAVY = '#060b1c'
// Multiplied into the Toner: its white land comes out slate, its black sea and labels stay black
const TONER_TINT = '#55607f'

const [lng, lat] = KOBE
// The course (out west along the shore to Tarumi and back), then the globe (Kobe in the
// middle, Europe and America over the edge)
const COURSE_SHOT = { lng: 135.1, lat: 34.645, height: 0, distance: 26_000, heading: 0, pitch: -62, roll: 0 }
const GLOBE_SHOT = { lng: lng - 10, lat: lat - 6, height: 0, distance: 15_000_000, heading: 0, pitch: -88, roll: 0 }
// The home dots grow as the camera comes down: ×1 from this height (m) up, ×MAX_SCALE at
// CLOSE_HEIGHT and below, log-interpolated in between
const FAR_HEIGHT = 2_500_000
const CLOSE_HEIGHT = 100_000
const MAX_SCALE = 2.6
// The gun goes this long (s) into the piece, and the whole field is across the line within
// START_SPREAD hours of the race (so I'm off well before I first ask)
const GUN = 0.2
const START_SPREAD = 0.12

// My photos, where along the course (km) I took them
const PHOTOS = [
  { src: `${dataBase}/photos/start.jpg`, km: 0, alt: 'Runners in rain ponchos packed into Flower Road, waiting for the start' },
  // (provisional: the photo has no location or time left in it)
  { src: `${dataBase}/photos/course.jpg`, km: 27, alt: 'Runners from behind on a wet road under power lines, a railway wall on the left' },
]
// The photos and the bubbles show from this camera height (m) down, fully from FULL down
const CLOSE_SHOW = 150_000
const CLOSE_FULL = 50_000
// My finish time (h), from my watch
const MY_TIME = 4.36
// Bubbles up at once, at most; and the runners around me who answer
const BUBBLES = 14
const NEAR_ME = 400

// The minimap: Japan and its neighbours on Toner's zoom 5 tiles, in those tiles' pixels
const MINI_ZOOM = 5
const MINI = { west: 119, east: 146, south: 24, north: 46 }
const worldPx = (lng: number, lat: number): [number, number] => {
  const n = 256 * 2 ** MINI_ZOOM
  const s = Math.sin((lat * Math.PI) / 180)
  return [((lng + 180) / 360) * n, (0.5 - Math.log((1 + s) / (1 - s)) / (4 * Math.PI)) * n]
}
const [miniX0, miniY0] = worldPx(MINI.west, MINI.north)
const [miniX1, miniY1] = worldPx(MINI.east, MINI.south)
const miniViewBox = `${miniX0} ${miniY0} ${miniX1 - miniX0} ${miniY1 - miniY0}`
const miniTiles: { href: string; x: number; y: number }[] = []
for (let x = Math.floor(miniX0 / 256); x <= Math.floor(miniX1 / 256); x++) {
  for (let y = Math.floor(miniY0 / 256); y <= Math.floor(miniY1 / 256); y++) {
    miniTiles.push({ href: `${TONER_HOST}/${MINI_ZOOM}/${x}/${y}.png`, x: x * 256, y: y * 256 })
  }
}
const miniKobe = worldPx(lng, lat)

/** The point `km` along the course */
function alongCourse(course: [number, number][], km: number): [number, number] {
  let left = km * 1000
  for (let i = 1; i < course.length; i++) {
    const [a, b] = [course[i - 1]!, course[i]!]
    const dx = (b[0] - a[0]) * 111_320 * Math.cos((a[1] * Math.PI) / 180)
    const dy = (b[1] - a[1]) * 110_574
    const d = Math.hypot(dx, dy)
    if (left <= d) return [a[0] + ((b[0] - a[0]) * left) / d, a[1] + ((b[1] - a[1]) * left) / d]
    left -= d
  }
  return course[course.length - 1]!
}

const container = ref<HTMLDivElement>()
const cards = ref<HTMLButtonElement[]>([])
const bubbleEls = ref<HTMLDivElement[]>([])
const opened = ref<(typeof PHOTOS)[number]>()
// The homes told so far, on the minimap ([x, y] in its pixels), and how the minimap and
// the watermark fade
const miniDots = shallowRef<[number, number][]>([])
const miniOpacity = ref(1)
const watermarkOpacity = ref(0)
let view: ThreeView<DefaultDescriptions> | undefined
let timer: ReturnType<typeof setTimeout> | undefined

onMounted(async () => {
  const v = new ThreeView<DefaultDescriptions>({
    container: container.value!,
    backgroundColor: new Color().setStyle(NAVY),
    animation: true,
    // Each tile's mesh in this many strips a side (Navara's default, 10, leaves the whole
    // globe, a few tiles from afar, visibly polygonal at its edge)
    segments: 40,
  })
  view = v
  v.addPlugin(new DefaultPlugin())
  const [course, data] = await Promise.all([
    fetch(`${dataBase}/course.json`).then((r) => r.json() as Promise<[number, number][]>),
    fetch(`${dataBase}/homes.json`).then((r) => r.json() as Promise<Homes>),
    v.init(),
  ])
  if (view !== v) return // unmounted while initializing
  v.registerMesh('limbGlow', LimbGlowMeshDesc)
  v.registerMesh('starfield', StarfieldMeshDesc)
  v.registerMesh('arcGlow', ArcGlowMeshDesc)
  v.registerMesh('courseFlow', CourseFlowMeshDesc)

  v.globe.color = new Color().setStyle(NAVY)
  v.setCamera(COURSE_SHOT)

  const bloom = v.addEffect({ selectiveBloom: { strength: 1.1, radius: 0.5, threshold: 0 } })

  // (typed separately: the view's mesh config union only knows the DefaultPlugin descriptors)
  const limbGlow: LimbGlowConfig = { limbGlow: { color: new Color().setStyle('#5b86ff'), intensity: 0.8, scaleHeight: 80_000 } }
  v.addMesh<LimbGlowMeshDesc>(limbGlow)
  const starfield: StarfieldConfig = { starfield: {} }
  v.addMesh<StarfieldMeshDesc>(starfield)

  v.addLayer({ type: 'terrain', ellipsoid: {} })
  const toner = v.addSource({ type: 'raster-tile', url: TONER, maxZoom: 18 })
  v.addLayer({ type: 'raster', source: toner, raster: { color: new Color().setStyle(TONER_TINT) } })

  const story = new WhereFrom(data)
  const homes = data.homes.map(([lng, lat]) => [lng, lat] as [number, number])
  const miniHomes = story.order.map((h) => worldPx(...homes[h]!))

  // (no bloom: the race reads flat, under the glowing arcs)
  const courseFlow: CourseFlowConfig = { courseFlow: { course, me: MY_TIME, startSpread: START_SPREAD } }
  const crowd = v.addMesh<CourseFlowMeshDesc>(courseFlow)
  const nearMe = crowd.ref.nearMe(NEAR_ME)
  const arcGlow: ArcGlowConfig = { effectIds: [bloom.id], arcGlow: { homes, to: KOBE, order: story.rank } }
  const arcs = v.addMesh<ArcGlowMeshDesc>(arcGlow)

  const start = performance.now()
  let clock = 0 // s into the piece
  v.on('preUpdate', () => {
    clock = (performance.now() - start) / 1000
    arcs.ref.tick(clock)
    crowd.ref.tick(clock - GUN)

    const revealed = story.revealed(clock)
    arcs.ref.setRevealed(revealed)
    arcs.ref.setGrow(story.grow(clock))
    if (Math.floor(revealed) !== miniDots.value.length) miniDots.value = miniHomes.slice(0, Math.floor(revealed))
    miniOpacity.value = story.minimap(clock)
    watermarkOpacity.value = story.watermark(clock)

    // (the camera's position is missing until the view is ready: keep the size till then)
    let height: number
    try {
      height = v.camera.positionGeographic.height
    } catch {
      return
    }
    const h = Math.min(FAR_HEIGHT, Math.max(CLOSE_HEIGHT, height))
    arcs.ref.setHomeScale(1 + ((MAX_SCALE - 1) * Math.log(FAR_HEIGHT / h)) / Math.log(FAR_HEIGHT / CLOSE_HEIGHT))
  })

  // The pull-back, given up if the camera's been grabbed by then
  let grabbed = false
  const grab = () => {
    grabbed = true
    clearTimeout(timer)
  }
  for (const type of ['pointerdown', 'wheel', 'touchstart'] as const) {
    container.value?.addEventListener(type, grab, { passive: true })
  }
  timer = setTimeout(() => {
    if (!grabbed && view === v) v.flyTo(GLOBE_SHOT, { duration: PULL_BACK.duration * 1000, easing: 'cubicInOut' })
  }, PULL_BACK.at * 1000)

  // The photos, pinned over where they were taken; the bubbles over who's talking
  const photoAt = PHOTOS.map(({ km }) => {
    const [lng, lat] = alongCourse(course, km)
    return geodeticToVector3({ lng, lat, height: 0 })
  })
  const at = new Vector3()
  v.on('preRender', () => {
    const box = container.value
    if (!box) return
    let height = Infinity
    try {
      height = v.camera.positionGeographic.height
    } catch {}
    const show = Math.min(1, Math.max(0, (CLOSE_SHOW - height) / (CLOSE_SHOW - CLOSE_FULL)))
    // On screen (px) or not
    const toScreen = (p: Vector3): [number, number] | undefined => {
      p.project(v.camera.raw)
      if (p.z >= 1) return undefined
      return [((p.x + 1) / 2) * box.clientWidth, ((1 - p.y) / 2) * box.clientHeight]
    }

    cards.value.forEach((el, i) => {
      const xy = show > 0 ? toScreen(at.copy(photoAt[i]!)) : undefined
      el.style.visibility = xy ? 'visible' : 'hidden'
      if (!xy) return
      el.style.transform = `translate(${xy[0]}px, ${xy[1]}px)`
      el.style.opacity = String(show)
    })

    const raceTime = clock - GUN
    const up = show > 0 ? story.bubbles(clock) : []
    let n = 0
    for (const b of up) {
      const el = bubbleEls.value[n]
      if (!el) break
      const there = b.who === 'me' ? crowd.ref.meAt(raceTime, at) : crowd.ref.runnerAt(nearMe[b.who % nearMe.length]!, raceTime, at)
      const xy = there ? toScreen(at) : undefined
      if (!xy) continue
      n++
      if (el.textContent !== b.text) el.textContent = b.text
      el.classList.toggle('answer', b.who !== 'me')
      el.style.visibility = 'visible'
      el.style.transform = `translate(${xy[0]}px, ${xy[1]}px) scale(${0.6 + 0.4 * b.pop})`
      el.style.opacity = String(show * b.pop)
    }
    for (; n < bubbleEls.value.length; n++) bubbleEls.value[n]!.style.visibility = 'hidden'
  })

  v.attribution?.add([
    {
      attributionHtml:
        '<a href="https://tile.openstreetmap.jp/">OpenStreetMap Japan</a> · © <a href="https://www.openmaptiles.org/">OpenMapTiles</a> · © <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors',
    },
  ])
})

onBeforeUnmount(() => {
  clearTimeout(timer)
  view?.dispose()
  view = undefined
})
</script>

<template>
  <div class="map-canvas day16">
    <div ref="container" class="map-canvas" />
    <div class="photos">
      <button
        v-for="(photo, i) in PHOTOS"
        :key="photo.src"
        ref="cards"
        type="button"
        class="card"
        :style="{ '--tilt': `${i % 2 ? 4 : -5}deg` }"
        @click="opened = photo"
      >
        <img :src="photo.src" :alt="photo.alt" />
      </button>
      <!-- (after the photos, so over them) -->
      <div v-for="i in BUBBLES" :key="i" ref="bubbleEls" class="bubble" />
    </div>
    <div v-if="opened" class="lightbox" @click="opened = undefined">
      <img :src="opened.src" :alt="opened.alt" />
    </div>
    <!-- Where the answers come from, while the camera's down on the course -->
    <svg v-show="miniOpacity > 0" class="minimap" :viewBox="miniViewBox" :style="{ opacity: miniOpacity }" aria-hidden="true">
      <image v-for="tile in miniTiles" :key="tile.href" :href="tile.href" :x="tile.x" :y="tile.y" width="256" height="256" />
      <rect class="tint" :x="miniX0" :y="miniY0" :width="miniX1 - miniX0" :height="miniY1 - miniY0" />
      <circle class="kobe" :cx="miniKobe[0]" :cy="miniKobe[1]" r="7" />
      <circle v-for="([x, y], i) in miniDots" :key="i" class="home" :cx="x" :cy="y" r="3.5" />
    </svg>
    <!-- I never asked anyone, so: an impression, not data -->
    <div class="watermark" aria-hidden="true" :style="{ opacity: watermarkOpacity }">
      <span>I DIDN’T ASK ANYONE</span>
      <small>(couldn’t find the nerve)</small>
    </div>
  </div>
</template>


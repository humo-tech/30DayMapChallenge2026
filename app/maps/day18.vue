// Day 18: Null — the view from the Tokaido Shinkansen's right-hand window, westbound past Mt.
// Fuji, on GSI's DEM and aerial photo. Partway along, the mountain's elevations go null and it is
// gone: the same ride on, past the Fuji River, as if there had never been a mountain there.
// The terrain under it is already Fuji-less (lib/nullDem.ts); the mountain is a mesh of its own
// over it (lib/FujiMountainMeshDesc.ts), so it can go in a moment.
// Seen through the car's window: a frame round the view, and on the glass a film of dust, greasy
// smudges that blur what is behind them, and the cabin's light reflected faintly in it (CSS only,
// laid over the canvas; ?clean=1 takes it all off)
import ThreeView, { Color, JAPAN_GSI_ELEVATION_DECODER } from '@navaramap/three'
import { DefaultPlugin, type DefaultDescriptions } from '@navaramap/three-default-plugin'
import { Color as ThreeColor, TextureLoader } from 'three'
import { FujiMountainMeshDesc, type FujiMountainConfig } from './lib/FujiMountainMeshDesc'
import { HazeEffectDesc, type HazeConfig } from './lib/HazeEffectDesc'
import { SkyDomeMeshDesc, type SkyDomeConfig } from './lib/SkyDomeMeshDesc'
import { installNullDem, NULL_DEM_URL, readNullGrid } from './lib/nullDem'

// Generated by scripts/day18/null_fuji.py
const baseURL = useRuntimeConfig().app.baseURL
const dataBase = `${baseURL}data/day18`

const GSI = 'https://cyberjapandata.gsi.go.jp/xyz'

// The ride, in m along the track from its start (east of Shin-Fuji): the mountain goes at
// VANISH_AT, over VANISH_S s; the train then runs on into the first tunnel, where the screen is
// dark for DARK_S s before the ride starts over, coming out of the dark over LIGHT_S s
const VANISH_AT = 6000
const VANISH_S = 0.6
const DARK_S = 2.5
const LIGHT_S = 2
// The train's speed (m/s): about twice a Nozomi's 285 km/h
const SPEED = 160
// Out of the right-hand window (square to the track), the eyes drawn this far round to the
// mountain (or where it was), a touch up, through a lens a little longer than the screen's own
const SUMMIT = { lng: 138.7274, lat: 35.3606 }
const GAZE = 0.6
const PITCH = 1.5
const FOV = 32
// A clear day's sky, pale at the horizon
const SKY = { horizon: '#dfe6ea', zenith: '#6f9ccc' }
// ... and the air between: the far ground fades into it over this many m
const HAZE = { color: '#d3dde4', reach: 45_000, max: 0.75 }

// The minimap: GSI's pale map at z10 over this extent, the line, the train and where it looks
const MINIMAP = { z: 10, west: 138.45, east: 138.95, north: 35.45, south: 35.0 }

type Layout = { z: number; x0: number; y0: number; cols: number; rows: number }
type Meta = {
  mesh: Layout
  fill: Layout
  track: { line: [number, number][]; step: number; points: [number, number, number][]; tunnels: [number, number][] }
}

const WGS84_A = 6378137
const WGS84_E2 = (1 / 298.257223563) * (2 - 1 / 298.257223563)
function ecef(lng: number, lat: number, h: number): [number, number, number] {
  const [lo, la] = [(lng * Math.PI) / 180, (lat * Math.PI) / 180]
  const n = WGS84_A / Math.sqrt(1 - WGS84_E2 * Math.sin(la) ** 2)
  return [(n + h) * Math.cos(la) * Math.cos(lo), (n + h) * Math.cos(la) * Math.sin(lo), (n * (1 - WGS84_E2) + h) * Math.sin(la)]
}
/** A Web Mercator pixel's centre at zoom z */
function lngLatOf(x: number, y: number, z: number): [number, number] {
  const n = 256 * 2 ** z
  return [(x / n) * 360 - 180, (Math.atan(Math.sinh(Math.PI * (1 - (2 * y) / n))) * 180) / Math.PI]
}

/** The mountain's grid as vertices in its West-Up-North frame, round its middle at sea level */
function mountainVertices(layout: Layout, heights: Uint16Array) {
  const { z, x0, y0, cols, rows } = layout
  const [lng0, lat0] = lngLatOf(x0 + cols / 2, y0 + rows / 2, z)
  const origin = ecef(lng0, lat0, 0)
  const [lo, la] = [(lng0 * Math.PI) / 180, (lat0 * Math.PI) / 180]
  const east = [-Math.sin(lo), Math.cos(lo), 0]
  const north = [-Math.sin(la) * Math.cos(lo), -Math.sin(la) * Math.sin(lo), Math.cos(la)]
  const up = [Math.cos(la) * Math.cos(lo), Math.cos(la) * Math.sin(lo), Math.sin(la)]
  const vertices = new Float32Array(cols * rows * 3)
  const inside = new Uint8Array(cols * rows)
  for (let i = 0; i < rows; i++) {
    for (let j = 0; j < cols; j++) {
      const k = i * cols + j
      const h = heights[k]! / 10
      inside[k] = h > 0 ? 1 : 0
      const [lng, lat] = lngLatOf(x0 + j + 0.5, y0 + i + 0.5, z)
      const p = ecef(lng, lat, h)
      const d = [p[0] - origin[0], p[1] - origin[1], p[2] - origin[2]] as const
      const dot = (a: number[]) => d[0] * a[0]! + d[1] * a[1]! + d[2] * a[2]!
      vertices.set([-dot(east), dot(up), dot(north)], k * 3)
    }
  }
  return { origin: { lng: lng0, lat: lat0, height: 0 }, vertices, inside }
}

/** A point's Web Mercator pixel at zoom z, as [x, y] */
function pixelOf(lng: number, lat: number, z: number): [number, number] {
  const n = 256 * 2 ** z
  const la = (lat * Math.PI) / 180
  return [((lng + 180) / 360) * n, ((1 - Math.log(Math.tan(la) + 1 / Math.cos(la)) / Math.PI) / 2) * n]
}

// The minimap's frame, in z10 pixels from its top-left corner, and the tiles under it
const [mapX0, mapY0] = pixelOf(MINIMAP.west, MINIMAP.north, MINIMAP.z)
const [mapX1, mapY1] = pixelOf(MINIMAP.east, MINIMAP.south, MINIMAP.z)
const mapSize = { w: Math.round(mapX1 - mapX0), h: Math.round(mapY1 - mapY0) }
const onMap = (lng: number, lat: number) => {
  const [x, y] = pixelOf(lng, lat, MINIMAP.z)
  return [x - mapX0, y - mapY0] as const
}
const mapTiles: { href: string; x: number; y: number }[] = []
for (let ty = Math.floor(mapY0 / 256); ty <= Math.floor(mapY1 / 256); ty++) {
  for (let tx = Math.floor(mapX0 / 256); tx <= Math.floor(mapX1 / 256); tx++) {
    mapTiles.push({ href: `${GSI}/pale/${MINIMAP.z}/${tx}/${ty}.png`, x: tx * 256 - mapX0, y: ty * 256 - mapY0 })
  }
}
const summitOnMap = onMap(SUMMIT.lng, SUMMIT.lat)

const route = useRoute()
// ?clean=1: the view with no window round it
const clean = computed(() => route.query.clean === '1')
const container = ref<HTMLDivElement>()
const dark = ref(1)
const linePath = ref('')
const ridePath = ref('')
// The train on the minimap, the way it looks (deg) and how much of the mountain is left
const train = ref({ x: 0, y: 0, heading: 0 })
const presence = ref(1)
// The view's wedge on the minimap, from the train out along its heading
const VIEW_R = 200
const wedge = computed(() => {
  const { x, y, heading } = train.value
  const tip = (deg: number) => {
    const r = (deg * Math.PI) / 180
    return `${(x + VIEW_R * Math.sin(r)).toFixed(1)} ${(y - VIEW_R * Math.cos(r)).toFixed(1)}`
  }
  const half = (FOV * (window.innerWidth / window.innerHeight)) / 2
  return `M ${x.toFixed(1)} ${y.toFixed(1)} L ${tip(heading - half)} L ${tip(heading + half)} Z`
})
let view: ThreeView<DefaultDescriptions> | undefined
let uninstall: (() => void) | undefined

async function loadData() {
  const meta = (await fetch(`${dataBase}/fuji.json`).then((r) => r.json())) as Meta
  const [nullBin, heightsBin, photo] = await Promise.all([
    fetch(`${dataBase}/fuji_null.bin`).then((r) => r.arrayBuffer()),
    fetch(`${dataBase}/fuji_heights.bin`).then((r) => r.arrayBuffer()),
    new TextureLoader().loadAsync(`${dataBase}/fuji_ortho.jpg`),
  ])
  return { meta, grid: readNullGrid(meta.fill, nullBin), heights: new Uint16Array(heightsBin), photo }
}

onMounted(async () => {
  const data = await loadData()
  if (!container.value) return // unmounted while loading
  // The DEM's tiles go through it from here on: before the view asks for any
  uninstall = installNullDem(data.grid)

  const v = new ThreeView<DefaultDescriptions>({
    container: container.value,
    backgroundColor: new Color().setStyle(SKY.horizon),
    animation: true,
    pixelRatio: Math.min(window.devicePixelRatio || 1, 3),
  })
  view = v
  v.addPlugin(new DefaultPlugin())
  await v.init()
  if (view !== v) return // unmounted while initializing
  v.registerMesh('skyDome', SkyDomeMeshDesc)
  v.registerMesh('fujiMountain', FujiMountainMeshDesc)
  v.registerEffect('haze', HazeEffectDesc)

  // The track, and the camera at the window s m along it
  const { line, points, step, tunnels } = data.meta.track
  const end = (tunnels[0]?.[0] ?? points.length - 1) * step
  const pathOf = (pts: readonly (readonly number[])[]) =>
    pts.map(([lng, lat], k) => `${k ? 'L' : 'M'} ${onMap(lng!, lat!).map((c) => c.toFixed(1)).join(' ')}`).join(' ')
  linePath.value = pathOf(line)
  ridePath.value = pathOf(points.slice(0, Math.round(end / step) + 1))
  const at = (s: number) => {
    const u = Math.min(Math.max(s / step, 0), points.length - 1.001)
    const k = Math.floor(u)
    const f = u - k
    const [a, b] = [points[k]!, points[k + 1]!]
    return [a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f, a[2] + (b[2] - a[2]) * f] as const
  }
  const bearing = (a: readonly number[], b: readonly number[]) => {
    const dx = (b[0]! - a[0]!) * Math.cos((a[1]! * Math.PI) / 180)
    return (Math.atan2(dx, b[1]! - a[1]!) * 180) / Math.PI
  }
  const turn = (deg: number) => ((((deg + 180) % 360) + 360) % 360) - 180
  const cameraAt = (s: number, time: number) => {
    const [lng, lat, height] = at(s)
    const square = bearing(at(s - 60), at(s + 60)) + 90
    const heading = square + GAZE * turn(bearing([lng, lat], [SUMMIT.lng, SUMMIT.lat]) - square)
    // The car's sway: a slow roll and a faint shudder
    const roll = Math.sin(time * 1.3) * 0.15 + Math.sin(time * 7.1) * 0.03
    return { lng, lat, height, heading, pitch: PITCH + Math.sin(time * 5.3) * 0.04, roll }
  }
  v.camera.fov = FOV
  v.setCamera(cameraAt(0, 0))

  const [lng0, lat0] = points[0]!
  const skyConfig: SkyDomeConfig = { skyDome: {}, geodetic: { lng: lng0, lat: lat0, height: 0 } }
  v.addMesh<SkyDomeMeshDesc>(skyConfig).ref.setColors(new ThreeColor(SKY.horizon), new ThreeColor(SKY.zenith))
  v.addLight({ ambient: { intensity: 1.0 } })
  const hazeConfig: HazeConfig = { haze: {} }
  v.addEffect<HazeEffectDesc>(hazeConfig).ref.setHaze(new ThreeColor(HAZE.color), HAZE.reach, HAZE.max)

  const dem = v.addSource({
    type: 'raster-dem',
    url: NULL_DEM_URL,
    elevationDecoder: JAPAN_GSI_ELEVATION_DECODER(),
    tileSize: 256,
    maxZoom: 14,
  })
  v.addLayer({ type: 'terrain', source: dem })
  const photo = v.addSource({ type: 'raster-tile', url: `${GSI}/seamlessphoto/{z}/{x}/{y}.jpg`, maxZoom: 17 })
  v.addLayer({ type: 'raster', source: photo })

  const { origin, vertices, inside } = mountainVertices(data.meta.mesh, data.heights)
  const config: FujiMountainConfig = {
    geodetic: origin,
    fujiMountain: { vertices, inside, ...data.meta.mesh, photo: data.photo },
  }
  const mountain = v.addMesh<FujiMountainMeshDesc>(config)

  v.attribution?.add([
    { attributionHtml: '<a href="https://maps.gsi.go.jp/development/ichiran.html">出典：国土地理院</a>' },
    {
      attributionHtml:
        'Track: © <a href="https://overturemaps.org/">Overture Maps Foundation</a> · © <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors',
    },
  ])

  // ?s=<m> starts the ride that far along, ?speed=<m/s> runs it at that speed, for tuning
  const speed = Number(route.query.speed) || SPEED
  const startAt = Number(route.query.s) || 0
  const ride = end / speed // s from the start to the tunnel
  const round = ride + DARK_S
  const clock = performance.now() - (startAt / speed) * 1000
  const smooth = (x: number) => (x <= 0 ? 0 : x >= 1 ? 1 : x * x * (3 - 2 * x))

  v.on('preUpdate', () => {
    const now = (performance.now() - clock) / 1000
    const t = now % round
    const s = Math.min(t, ride) * speed
    const camera = cameraAt(s, now)
    v.setCamera(camera)
    presence.value = 1 - smooth((t - VANISH_AT / speed) / VANISH_S)
    mountain.ref.setPresence(presence.value)
    const [x, y] = onMap(camera.lng, camera.lat)
    train.value = { x, y, heading: camera.heading }
    // Dark in the tunnel, light again as the next round starts
    dark.value = t >= ride ? 1 : 1 - smooth(t / LIGHT_S)
  })
})

onBeforeUnmount(() => {
  view?.dispose()
  view = undefined
  uninstall?.()
  uninstall = undefined
})
</script>

